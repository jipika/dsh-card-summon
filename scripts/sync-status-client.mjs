import { readFileSync, writeFileSync } from "node:fs";
import { createStatusCompat } from "../lib/status-compat.js";

// The client entry is a ModuleLoader factory, not an ESM import graph. Embed the shared source deterministically.
const target = new URL("../lib/client.js", import.meta.url);
const source = readFileSync(target, "utf8");
const start = "// BEGIN STATUS COMPAT (generated by scripts/sync-status-client.mjs)";
const end = "// END STATUS COMPAT";
const a = source.indexOf(start);
const b = source.indexOf(end);
if (a < 0 || b < a) throw new Error("Missing status compatibility source markers");
const next = source.slice(0, a + start.length) + "\n" + createStatusCompat.toString() +
	"\nconst { normalizeStatusText } = createStatusCompat();\n\t\t\t" + source.slice(b);
if (process.argv.includes("--check")) {
	if (source !== next) throw new Error("Run node scripts/sync-status-client.mjs after changing status-compat.js");
} else if (source !== next) writeFileSync(target, next);
console.log("status adapter client source synchronized");
